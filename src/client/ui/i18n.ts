export type MsgKey = keyof typeof en;

export function t(key: Exclude<MsgKey, 'rules.list'>, params: Record<string, string | number> = {}): string {
  const s = en[key] as string;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''));
}

